#!/usr/bin/env python3
"""Restore lost PowerBuilder by-reference parameter flags.

Generated by deploy/parity/REF-PARAM-AUDIT.md (2026-11-02).
Every entry below is confirmed by a PUSH_LOCAL_ARGREF_LV instruction in
recovered/pcode plus the routine name table. Parameters that are merely
assigned through a by-value slot (PUSH_LOCAL_VAR_LV) are deliberately absent.

Sets "ref": true on the matching parameter in both:
    rebuild/web/public/data/classes/<file>.json
    rebuild/web/dist/data/classes/<file>.json

Idempotent: already-true parameters are counted, and a file is only written
when at least one flag actually changes.

Usage:
    python patch_ref_params.py --dry-run
    python patch_ref_params.py
    python patch_ref_params.py --root rebuild/web/public/data/classes
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

DEFAULT_ROOTS = [
    Path("rebuild/web/public/data/classes"),
    Path("rebuild/web/dist/data/classes"),
]

# (library, file, class, routine, signature, *parameters_to_set_ref)
CONFIRMED = [

]


def load(path: Path):
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def dump(path: Path, data) -> None:
    text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    path.write_text(text, encoding="utf-8")


def apply_root(root: Path, dry_run: bool) -> dict:
    stats = {
        "root": str(root),
        "files_changed": 0,
        "files_missing": 0,
        "params_set": 0,
        "params_already": 0,
        "routine_missing": 0,
        "signature_missing": 0,
        "param_missing": 0,
        "object_params": 0,
    }
    warnings: list[str] = []
    cache: dict[Path, dict] = {}
    dirty: set[Path] = set()

    for spec in CONFIRMED:
        lib, file, cls, routine, signature = spec[:5]
        wanted = spec[5:]
        path = root / (file + ".json")
        if path not in cache:
            if not path.exists():
                stats["files_missing"] += 1
                if len(warnings) < 50:
                    warnings.append(f"missing file: {path}")
                cache[path] = None  # type: ignore[assignment]
            else:
                cache[path] = load(path)
        data = cache[path]
        if data is None:
            continue

        routines = (data.get("routines") or {}).get(cls) or {}
        entries = routines.get(routine)
        if not entries:
            stats["routine_missing"] += 1
            if len(warnings) < 50:
                warnings.append(f"{path}: no routine {cls}.{routine}")
            continue

        matches = [
            e for e in entries
            if ",".join(str(p.get("n", "")) for p in e.get("params") or []) == signature
        ]
        if len(matches) != 1:
            stats["signature_missing"] += 1
            if len(warnings) < 50:
                warnings.append(
                    f"{path}: {cls}.{routine}({signature}) matched {len(matches)} entries"
                )
            continue

        entry = matches[0]
        for name in wanted:
            target = next((p for p in entry.get("params") or [] if p.get("n") == name), None)
            if target is None:
                stats["param_missing"] += 1
                if len(warnings) < 50:
                    warnings.append(f"{path}: {cls}.{routine} has no param {name}")
                continue
            if target.get("ref") is True:
                stats["params_already"] += 1
            else:
                target["ref"] = True
                stats["params_set"] += 1
                dirty.add(path)

    if not dry_run:
        for path in sorted(dirty):
            dump(path, cache[path])
    stats["files_changed"] = len(dirty)
    stats["warnings"] = warnings
    return stats


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true", help="report without writing")
    ap.add_argument("--root", action="append", default=None,
                    help="class JSON root (repeatable; default: public + dist)")
    ap.add_argument("--strict", action="store_true", help="exit 1 on any warning")
    args = ap.parse_args(argv)

    roots = [Path(r) for r in args.root] if args.root else DEFAULT_ROOTS
    grand = {"files_changed": 0, "params_set": 0, "params_already": 0}
    all_warnings: list[str] = []

    for root in roots:
        if not root.exists():
            print(f"SKIP  {root} (does not exist)")
            continue
        st = apply_root(root, args.dry_run)
        grand["files_changed"] += st["files_changed"]
        grand["params_set"] += st["params_set"]
        grand["params_already"] += st["params_already"]
        all_warnings.extend(st["warnings"])
        mode = "DRY RUN" if args.dry_run else "APPLIED"
        print(f"[{mode}] {root}")
        print(f"  files changed : {st['files_changed']}")
        print(f"  params set    : {st['params_set']}")
        print(f"  already true  : {st['params_already']}")
        for key in ("files_missing", "routine_missing", "signature_missing", "param_missing"):
            if st[key]:
                print(f"  {key:17s}: {st[key]}")
        if st["warnings"]:
            print("  warnings:")
            for w in st["warnings"]:
                print(f"    - {w}")

    print("-" * 60)
    print(f"TOTAL parameters set   : {grand['params_set']}")
    print(f"TOTAL already true     : {grand['params_already']}")
    print(f"TOTAL files changed    : {grand['files_changed']}")
    if all_warnings:
        print(f"TOTAL warnings         : {len(all_warnings)}")
    if args.strict and all_warnings:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
