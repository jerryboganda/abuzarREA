import json,collections
rows=json.load(open("dw_metrics.json",encoding="utf-8"))
print("total",len(rows))
print("kind",collections.Counter(r.get("kind") for r in rows))
print("noretr",sum(1 for r in rows if not r.get("has_retrieve")))
print("updatable",sum(1 for r in rows if r.get("updatable")))
print("asneeded",sum(1 for r in rows if r.get("retrieve_asneeded")))
print("rows_setting",sum(1 for r in rows if r.get("rows_setting")))
print("buffer_setting",sum(1 for r in rows if r.get("buffer_setting")))
print("sort",sum(1 for r in rows if r.get("sort")))
print("filter",sum(1 for r in rows if r.get("filter")))
print("nested",sum(1 for r in rows if r.get("n_nested")))
print("crosstab",sum(1 for r in rows if r.get("n_crosstab")))
print("graph",sum(1 for r in rows if r.get("n_graph")))
print("select_star",sum(1 for r in rows if (r.get("sql") or {}).get("select_star")))
print("distinct",sum(1 for r in rows if (r.get("sql") or {}).get("distinct")))
print("top",sum(1 for r in rows if (r.get("sql") or {}).get("top")))
print("orderby",sum(1 for r in rows if (r.get("sql") or {}).get("order_by")))
print("groupby",sum(1 for r in rows if (r.get("sql") or {}).get("group_by")))
print("union",sum(1 for r in rows if (r.get("sql") or {}).get("union")))
print("subq",sum(1 for r in rows if (r.get("sql") or {}).get("subqueries")))
print("temps",sum(1 for r in rows if (r.get("sql") or {}).get("temp_table")))
print("exec",sum(1 for r in rows if (r.get("sql") or {}).get("exec")))
print("nolock",sum(1 for r in rows if (r.get("sql") or {}).get("nolock")))
print("size>100k",sum(1 for r in rows if r["bytes"]>100000))
print()
